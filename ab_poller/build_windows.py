#!/usr/bin/env python3
"""Build the PLC Toolkit GUI as a Windows executable (PySide6 + pylogix).

Run from ab_poller/:
    python build_windows.py

Output:
    ../PLC_Toolkit.exe
    ../dist_package/PLC_Toolkit/   (ready-to-copy folder)
    ../dist_package/PLC_Toolkit_Windows.zip
"""

from __future__ import annotations

import json
import shutil
import subprocess
import sys
import tempfile
import time
from dataclasses import asdict
from datetime import datetime, timezone
from pathlib import Path

# Launchers live in extras/, so they target the exe in the parent folder
# and set the working directory to the app root for portable paths.
PACKAGE_LAUNCHER = r"""@echo off
rem Optional launcher — double-click PLC_Toolkit.exe in the parent folder instead.
cd /d "%~dp0.."
start "" "%CD%\PLC_Toolkit.exe"
exit /b 0
"""

PACKAGE_VBS = """Set fso = CreateObject("Scripting.FileSystemObject")
Set sh = CreateObject("WScript.Shell")
scriptDir = fso.GetParentFolderName(WScript.ScriptFullName)
appDir = fso.GetParentFolderName(scriptDir)
sh.CurrentDirectory = appDir
sh.Run Chr(34) & appDir & "\\PLC_Toolkit.exe" & Chr(34), 1, False
"""


def _sync_logo_asset(root: Path, repo_root: Path) -> Path:
    """Ensure clr-logo.png lives under plc_toolkit/assets for PyInstaller."""
    logo_src = repo_root / "mockups" / "assets" / "clr-logo.png"
    logo_dst = root / "plc_toolkit" / "assets" / "clr-logo.png"
    logo_dst.parent.mkdir(parents=True, exist_ok=True)
    if not logo_src.is_file():
        raise FileNotFoundError(
            f"Logo not found: {logo_src}\n"
            "Expected mockups/assets/clr-logo.png at repo root."
        )
    shutil.copy2(logo_src, logo_dst)
    return logo_dst


def _generate_splash_png(root: Path) -> Path:
    """Write splash.png for PyInstaller bootloader splash."""
    import os

    splash_dst = root / "plc_toolkit" / "assets" / "splash.png"
    # Render under the real Windows platform so system fonts are available
    # and the baked-in title/subtitle render as text (not tofu boxes). The
    # headless 'offscreen' platform has no fonts.
    os.environ["QT_QPA_PLATFORM"] = "windows"
    if str(root) not in sys.path:
        sys.path.insert(0, str(root))
    from PySide6.QtWidgets import QApplication

    from plc_toolkit.splash import splash_pixmap

    app = QApplication([])
    if not splash_pixmap(with_text=True).save(str(splash_dst), "PNG"):
        raise RuntimeError(f"Could not write {splash_dst}")
    app.quit()
    return splash_dst


def _write_spec(root: Path, logo_dst: Path, splash_dst: Path) -> Path:
    from PyInstaller.utils.hooks import collect_all, collect_submodules

    pyside_datas, pyside_binaries, pyside_hidden = collect_all("PySide6")
    plc_hidden = collect_submodules("plc_toolkit")
    plck_hidden = collect_submodules("plck")

    rel_logo = logo_dst.relative_to(root).as_posix()
    rel_splash = splash_dst.relative_to(root).as_posix()
    datas = [
        (rel_logo, "plc_toolkit/assets"),
        (rel_splash, "plc_toolkit/assets"),
        *pyside_datas,
    ]
    hiddenimports = sorted(
        set(
            [
                "pylogix",
                "openpyxl",
                "openpyxl.styles",
                "openpyxl.cell",
                "openpyxl.workbook",
                "sqlite3",
                *pyside_hidden,
                *plc_hidden,
                *plck_hidden,
            ]
        )
    )

    spec = root / "PLC_Toolkit.spec"

    spec.write_text(
        f"""# -*- mode: python ; coding: utf-8 -*-
# Generated by build_windows.py — do not edit by hand.

block_cipher = None

a = Analysis(
    ['plc_toolkit/__main__.py'],
    pathex=['.'],
    binaries={pyside_binaries!r},
    datas={datas!r},
    hiddenimports={hiddenimports!r},
    hookspath=[],
    hooksconfig={{}},
    runtime_hooks=[],
    excludes=['matplotlib', 'numpy', 'pandas', 'pycomm3'],
    win_no_prefer_redirects=False,
    win_private_assemblies=False,
    cipher=block_cipher,
    noarchive=False,
)

pyz = PYZ(a.pure, a.zipped_data, cipher=block_cipher)

# Bootloader splash — shows instantly while the onefile exe unpacks,
# before Python/Qt start. Requires Tcl/Tk, so 'tkinter' must NOT be in
# excludes, and EXE must include both `splash` and `splash.binaries`.
splash = Splash(
    '{rel_splash}',
    binaries=a.binaries,
    datas=a.datas,
    text_pos=(12, 262),
    text_size=8,
    text_color='#8FA4B8',
    text_default='Loading PLC Toolkit',
    minify_script=True,
    always_on_top=True,
)

exe = EXE(
    pyz,
    a.scripts,
    splash,
    splash.binaries,
    a.binaries,
    a.zipfiles,
    a.datas,
    name='PLC_Toolkit',
    debug=False,
    bootloader_ignore_signals=False,
    strip=False,
    upx=False,
    upx_exclude=[],
    runtime_tmpdir=None,
    console=False,
    disable_windowed_traceback=False,
    argv_emulation=False,
    target_arch=None,
    codesign_identity=None,
    entitlements_file=None,
)
""",
        encoding="utf-8",
    )
    return spec



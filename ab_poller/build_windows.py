def assemble_package(dist_exe: Path, root: Path, repo_root: Path) -> tuple[Path, Path]:
    """Build extract-and-run folder + zip. Returns (folder, zip_path)."""
    sys.path.insert(0, str(root))
    from plc_toolkit.settings_store import AppSettings

    assets_src = root / "plc_toolkit" / "assets"
    package_root = repo_root / "dist_package"
    package_dir = package_root / "PLC_Toolkit"
    if package_dir.exists():
        stale = package_root / f"_stale_{int(time.time())}"
        try:
            package_dir.rename(stale)
            shutil.rmtree(stale, ignore_errors=True)
        except OSError:
            shutil.rmtree(package_dir, ignore_errors=True)
    package_dir.mkdir(parents=True, exist_ok=True)

    # Extracted root stays clean: only PLC_Toolkit.exe + folders.
    shutil.copy2(dist_exe, package_dir / "PLC_Toolkit.exe")
    if assets_src.is_dir():
        shutil.copytree(assets_src, package_dir / "assets")
    (package_dir / "data").mkdir()
    (package_dir / "scans").mkdir()
    (package_dir / "exports").mkdir()

    extras_dir = package_dir / "extras"
    extras_dir.mkdir()
    (extras_dir / "Run_Toolkit.bat").write_text(PACKAGE_LAUNCHER, encoding="utf-8")
    (extras_dir / "Launch PLC Toolkit.vbs").write_text(PACKAGE_VBS, encoding="utf-8")
    _write_quick_start(extras_dir / "Quick_Start.txt")
    _write_mvp_pilot(extras_dir / "MVP_PILOT.txt")

    (package_dir / "data" / "portable.marker").write_text(
        f"PLC Toolkit portable package\nBuilt: "
        f"{datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M UTC')}\n",
        encoding="utf-8",
    )
    (package_dir / "data" / "settings.json").write_text(
        json.dumps(asdict(AppSettings()), indent=2),
        encoding="utf-8",
    )

    # Archive the *contents* of package_dir at the zip root (base_dir=".")
    # so extracting PLC_Toolkit.zip yields a single PLC_Toolkit\ folder
    # (named from the zip) with the exe directly inside — no nested folder.
    zip_base = package_root / "PLC_Toolkit"
    if zip_base.with_suffix(".zip").is_file():
        zip_base.with_suffix(".zip").unlink()
    archive = shutil.make_archive(str(zip_base), "zip", root_dir=str(package_dir))
    return package_dir, Path(archive)


def main() -> int:
    root = Path(__file__).resolve().parent
    repo_root = root.parent
    required = ["pyinstaller", "pylogix", "PySide6"]
    for pkg in required:
        try:
            __import__(pkg if pkg != "PySide6" else "PySide6")
        except ImportError:
            subprocess.check_call(
                [sys.executable, "-m", "pip", "install", pkg, "openpyxl"]
            )
            break

    logo_dst = _sync_logo_asset(root, repo_root)
    splash_dst = _generate_splash_png(root)
    spec = _write_spec(root, logo_dst, splash_dst)

    dist_dir = root / "dist"
    dist_dir.mkdir(exist_ok=True)
    work_dir = Path(tempfile.gettempdir()) / "plc_toolkit_pyinstaller"
    if work_dir.exists():
        shutil.rmtree(work_dir, ignore_errors=True)
    work_dir.mkdir(parents=True, exist_ok=True)

    try:
        subprocess.check_call(
            [
                sys.executable,
                "-m",
                "PyInstaller",
                str(spec),
                "--distpath",
                str(dist_dir),
                "--workpath",
                str(work_dir),
            ],
            cwd=str(root),
        )
    except subprocess.CalledProcessError:
        dist_exe = dist_dir / "PLC_Toolkit.exe"
        if not dist_exe.is_file():
            print(
                "PyInstaller failed and no existing dist/PLC_Toolkit.exe was found."
            )
            return 1
        print(
            "PyInstaller failed (often OneDrive lock on build/); "
            "using existing dist/PLC_Toolkit.exe for packaging."
        )

    dist_exe = root / "dist" / "PLC_Toolkit.exe"
    if not dist_exe.is_file():
        print("Build finished but dist/PLC_Toolkit.exe not found.")
        return 1

    dest = repo_root / "PLC_Toolkit.exe"
    if dest.is_file():
        shutil.copy2(dest, dest.with_suffix(".exe.bak"))
    shutil.copy2(dist_exe, dest)
    print(f"Built: {dest}")

    package_dir, zip_path = assemble_package(dist_exe, root, repo_root)
    print(f"Portable folder: {package_dir}")
    print(f"Portable zip:    {zip_path}")
    print("Deploy: extract the zip; users double-click PLC_Toolkit.exe")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
